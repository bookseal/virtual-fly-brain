const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 const base=process.env.FLY_UI_BASE||'http://localhost:8765';
 await page.goto(base+'/#experiments?run=20261015-220404',{waitUntil:'domcontentloaded'});
 await page.locator('[data-path-load]').waitFor();
 // A failed download must preserve a working retry button.
 let fail=true;await page.route('**/evaluations/*.json',route=>{if(fail)return route.abort();return route.continue();});
 await page.locator('[data-path-load]').click();
 await page.getByText(/다시 시도할 수 있습니다/).waitFor();fail=false;
 await page.locator('[data-path-load]').click();
 await page.locator('[data-path-content]:not([hidden])').waitFor();
 if(await page.locator('[data-path-seed] option').count()!==20)throw Error('Expected 20 paired conditions');
 if(!(await page.locator('.path-paired-summary').innerText()).includes('모방 후 PPO만 20'))throw Error('Paired failure/success result is wrong');
 await page.locator('[data-path-seed]').selectOption('10005');
 await page.locator('[data-path-play]').click();
 await page.waitForFunction(()=>parseFloat(document.querySelector('[data-path-time]').value)>0.2);
 await page.locator('[data-path-play]').click();
 const time=await page.locator('[data-path-time]').innerText();
 await page.waitForTimeout(150);
 if(await page.locator('[data-path-time]').innerText()!==time)throw Error('Pause failed');
 await page.locator('[data-path-time-slider]').fill('1.5');
 if(await page.locator('[data-path-time]').innerText()!=='1.50초')throw Error('Seek did not update timestamp');
 for(const dot of await page.locator('[data-path-dot]').all())if(!Number.isFinite(Number(await dot.getAttribute('cx'))))throw Error('Invalid path position');
 await page.locator('[data-path-group]').selectOption('wide');
 if(await page.locator('[data-path-content]').isVisible())throw Error('Stale paths shown under new condition');
 await page.locator('[data-path-load]').click();await page.locator('[data-path-content]:not([hidden])').waitFor();
 if(!(await page.locator('.path-paired-summary').innerText()).includes('둘 다 도착 20'))throw Error('Wide diagnostic grouping incorrect');
 await page.locator('.trajectory-explorer').screenshot({path:'runs/20261015-220404/media/path-explorer-desktop.png'});
 await page.setViewportSize({width:390,height:844});await page.emulateMedia({reducedMotion:'reduce'});
 await page.locator('.trajectory-explorer').scrollIntoViewIfNeeded();
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 await page.locator('.trajectory-explorer').screenshot({path:'runs/20261015-220404/media/path-explorer-mobile.png'});
 if(await page.locator('[data-path-play]').getAttribute('aria-pressed')!=='false')throw Error('Unexpected automatic motion');
 if(errors.length)throw Error(errors.join('\n'));
 await browser.close();console.log('Measured paths: retry, 20 paired conditions, playback/pause/seek, condition isolation, wide results, mobile, no autoplay/errors PASS');
})().catch(e=>{console.error(e);process.exit(1)});
